@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly platformId = inject(PLATFORM_ID);
  private readonly document = inject(DOCUMENT);
  readonly language = signal<SiteLanguage>('en');

  constructor() {
    // Restore after hydration so the server and first client render use the same language.
    afterNextRender(() => {
      if (!isPlatformBrowser(this.platformId)) return;
      const stored = this.document.defaultView?.localStorage.getItem(STORAGE_KEY);
      if (stored === 'en' || stored === 'uk') this.setLanguage(stored);
      else this.document.documentElement.lang = this.language();
    });
  }

  setLanguage(language: SiteLanguage): void {
    this.language.set(language);
    if (!isPlatformBrowser(this.platformId)) return;
    this.document.documentElement.lang = language;
    this.document.defaultView?.localStorage.setItem(STORAGE_KEY, language);
  }

  t(source: string): string {
    if (this.language() !== 'uk') return source;
    if (ukrainian[source]) return ukrainian[source];

    const status = source.match(/^(.*) \((\d+|network error)\)\.$/);
    if (status && ukrainian[status[1]]) return `${ukrainian[status[1]]} (${status[2]}).`;

    let match = source.match(/^Server “(.+)” transferred\.$/);
    if (match) return `Сервер «${match[1]}» передано.`;
    match = source.match(/^Your plan is now (.+)\.$/);
    if (match) return `Ваш тариф: ${match[1]}.`;
    match = source.match(/^Invitation code created\. It expires (.+)\.$/);
    if (match) return `Код запрошення створено. Діє до ${match[1]}.`;
    match = source.match(/^(.+) was removed from the workspace\.$/);
    if (match) return `${match[1]}: учасника видалено з робочого простору.`;
    match = source.match(/^Workspace “(.+)” was deleted\.$/);
    if (match) return `Робочий простір «${match[1]}» видалено.`;
    match = source.match(/^Remove (.+) from this workspace\?$/);
    if (match) return `Видалити ${match[1]} із цього робочого простору?`;
    match = source.match(/^Delete workspace “(.+)”\? This cannot be undone\.$/);
    if (match) return `Видалити робочий простір «${match[1]}»? Цю дію неможливо скасувати.`;
    return source;
  }

  formatDate(value: string | number | Date, style: 'medium' | 'full' | 'time' = 'medium', utc = false): string {
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return '';
    const locale = this.language() === 'uk' ? 'uk-UA' : 'en-US';
    const options: Intl.DateTimeFormatOptions = style === 'time'
      ? { timeStyle: 'medium' }
      : style === 'full'
        ? { dateStyle: 'full', timeStyle: 'long' }
        : { dateStyle: 'medium', timeStyle: 'short' };
    if (utc) options.timeZone = 'UTC';
    return new Intl.DateTimeFormat(locale, options).format(date);
  }

  plural(count: number, noun: 'server' | 'group' | 'groupIn' | 'rule'): string {
    if (this.language() === 'en') {
      const english = noun === 'groupIn' ? 'group' : noun;
      return count === 1 ? english : `${english}s`;
    }
    const forms: Record<typeof noun, [string, string, string]> = {
      server: ['сервер', 'сервери', 'серверів'],
      group: ['група', 'групи', 'груп'],
      groupIn: ['групі', 'групах', 'групах'],
      rule: ['правило', 'правила', 'правил'],
    };
    const mod10 = count % 10;
    const mod100 = count % 100;
    const form = mod10 === 1 && mod100 !== 11 ? 0
      : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? 1 : 2;
    return forms[noun][form];
  }
}
